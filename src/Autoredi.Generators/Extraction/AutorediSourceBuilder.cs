namespace Autoredi.Generators.Extraction;

/// <summary>
/// The generated extension-class source plus any output-stage diagnostics
/// (name sanitization warnings, method-name collisions).
/// </summary>
internal sealed record GeneratedResult(string Source, ImmutableArray<Diagnostic> Diagnostics);

/// <summary>
/// Generates the IServiceCollection extension methods for Autoredi registrations.
/// Registrations use TryAdd semantics: they fill gaps and never override existing entries.
/// </summary>
internal static class AutorediSourceBuilder
{
    private const string MethodPrefix = "AddAutorediServices";

    public static GeneratedResult Generate(ImmutableArray<AutorediTarget> targets, string @namespace, string assemblyName)
    {
        var diagnostics = new List<Diagnostic>();
        var builder = new CodeBuilder();
        builder.AutoGenerated();
        builder.Using("System");
        builder.Using("System.Collections.Generic");
        builder.Using("Microsoft.Extensions.DependencyInjection");
        builder.Using("Microsoft.Extensions.DependencyInjection.Extensions");
        builder.Line();

        builder.Namespace(@namespace);

        var validTargets = targets.Where(t => t.IsValid).ToImmutableArray();
        // "All" is reserved for the cross-assembly aggregator emitted by AutorediAllServicesBuilder.
        HashSet<string> claimedNames = [with(StringComparer.Ordinal), $"{MethodPrefix}All"];
        var assemblySuffix = AutorediNaming.ToAssemblyMethodSuffix(assemblyName);

        builder.Class("public static partial", "AutorediServiceCollectionExtensions");
        builder.Block(b =>
        {
            if (validTargets.Any(t => !t.InterfaceTypes.IsEmpty))
            {
                GenerateTryAddHelper(b);
            }

            GenerateDefaultServicesMethod(b, validTargets);
            GenerateGroupMethods(b, validTargets, assemblySuffix, claimedNames, diagnostics);
            GenerateAssemblyWideServicesMethod(b, validTargets, assemblyName, assemblySuffix, claimedNames, diagnostics);
        });

        return new GeneratedResult(builder.ToString(), diagnostics.ToImmutableArray());
    }

    /// <summary>
    /// Emits the index type and the helper every interface registration goes through. The index
    /// lets each generated method look up existing descriptors in O(1) per descriptor instead
    /// of rescanning the services list, which keeps registration O(n) per generated method.
    /// A single flat hash set of (service type, key, implementation type) triples backs the
    /// index: one allocation per method instead of one per service type.
    /// Interface multiplicity is per assembly, so a plain TryAdd drops an implementation another
    /// assembly contributed, and a plain TryAddEnumerable lets a generated descriptor outrank a
    /// hand-written one. The index encodes one pass that separates the cases: a descriptor with
    /// no implementation type is an instance or factory registration, so a human already decided
    /// what resolves; an identical implementation type is a duplicate; anything else is another
    /// implementation and is kept.
    /// </summary>
    private static void GenerateTryAddHelper(CodeBuilder builder)
    {
        builder.Class("private sealed", "AutorediIndex");
        builder.Block(cls =>
        {
            cls.Line("private readonly HashSet<(Type ServiceType, object? ServiceKey, Type? ImplementationType)> entries = new();");
            cls.Line();
            cls.Line("private AutorediIndex(IServiceCollection services)");
            cls.Block(ctor =>
            {
                ctor.Line("foreach (var existing in services)");
                ctor.Block(body => body.Line("Add(existing);"));
            });
            cls.Line();
            cls.Line("internal static AutorediIndex Build(IServiceCollection services) => new AutorediIndex(services);");
            cls.Line();
            cls.Line("internal bool ContainsMatch(ServiceDescriptor descriptor)");
            cls.Block(match =>
            {
                // ImplementationType is null for instance and factory registrations, so a
                // hand-written one owns this service type and key. The same implementation type
                // is a duplicate. Any other implementation type is kept so implementations
                // contributed by other assemblies survive the aggregate. One hash lookup, no
                // nested hash sets.
                match.Line("return entries.Contains((descriptor.ServiceType, descriptor.ServiceKey, null))");
                match.Line("    || entries.Contains((descriptor.ServiceType, descriptor.ServiceKey, descriptor.ImplementationType));");
            });
            cls.Line();
            cls.Line("internal void Add(ServiceDescriptor descriptor)");
            cls.Block(add =>
            {
                add.Line("entries.Add((descriptor.ServiceType, descriptor.ServiceKey, descriptor.ImplementationType));");
            });
        });
        builder.Line();

        builder.Method("private static", "void", "TryAddAutorediDescriptor", "IServiceCollection services, AutorediIndex autorediIndex, ServiceDescriptor descriptor");
        builder.Block(b =>
        {
            b.Line("if (autorediIndex.ContainsMatch(descriptor))");
            b.Block(skip =>
            {
                skip.Line("return;");
            });
            b.Line();
            b.Line("services.Add(descriptor);");
            b.Line("autorediIndex.Add(descriptor);");
        });
        builder.Line();
    }

    private static void GenerateDefaultServicesMethod(
        CodeBuilder builder,
        ImmutableArray<AutorediTarget> targets)
    {
        GenerateDefaultServicesDocComment(builder);
        builder.Method("public static", "IServiceCollection", MethodPrefix, "this IServiceCollection services");
        builder.Block(b => EmitStandardBody(b, targets.Where(t => string.IsNullOrWhiteSpace(t.Group))));
        builder.Line();
    }

    /// <summary>
    /// Emits the shared method body: a null guard, and the descriptor index only when the
    /// method actually registers interfaces (an unused local would warn in consumer builds).
    /// </summary>
    private static void EmitStandardBody(CodeBuilder builder, IEnumerable<AutorediTarget> targets)
    {
        var materialized = targets as IReadOnlyCollection<AutorediTarget> ?? targets.ToList();
        builder.Line("if (services is null)");
        builder.Block(guard => guard.Line("throw new System.ArgumentNullException(nameof(services));"));
        if (materialized.Any(t => !t.InterfaceTypes.IsEmpty))
        {
            builder.Line("var autorediIndex = AutorediIndex.Build(services);");
        }

        EmitOrdered(builder, materialized);
        builder.Line("return services;");
    }

    private static void GenerateGroupMethods(
        CodeBuilder builder,
        ImmutableArray<AutorediTarget> targets,
        string assemblySuffix,
        HashSet<string> claimedNames,
        List<Diagnostic> diagnostics)
    {
        var groups = targets
            .Where(t => !string.IsNullOrWhiteSpace(t.Group))
            .Select(t => t.Group!)
            .Distinct()
            .OrderBy(g => g, StringComparer.Ordinal);

        foreach (var raw in groups)
        {
            var fragment = AutorediNaming.ToIdentifierFragment(raw);
            var ownerLocation = LocationOfFirst(targets, t => t.Group == raw);

            if (AutorediNaming.RequiresSanitization(raw))
            {
                diagnostics.Add(Diagnostic.Create(Diagnostics.InvalidGroupName, ownerLocation, raw, fragment));
            }

            if (string.Equals(fragment, assemblySuffix, StringComparison.Ordinal)
                || !claimedNames.Add($"{MethodPrefix}{fragment}"))
            {
                diagnostics.Add(Diagnostic.Create(Diagnostics.MethodNameCollision, ownerLocation, fragment));
                continue;
            }

            GenerateGroupDocComment(builder, raw);
            builder.Method("public static", "IServiceCollection", $"{MethodPrefix}{fragment}", "this IServiceCollection services");
            builder.Block(b => EmitStandardBody(b, targets.Where(t => t.Group == raw)));
            builder.Line();
        }
    }

    private static void GenerateAssemblyWideServicesMethod(
        CodeBuilder builder,
        ImmutableArray<AutorediTarget> targets,
        string assemblyName,
        string assemblySuffix,
        HashSet<string> claimedNames,
        List<Diagnostic> diagnostics)
    {
        if (!claimedNames.Add($"{MethodPrefix}{assemblySuffix}"))
        {
            // The reserved All method or a group already claimed this name. Point at the
            // winning group's first registration when there is one.
            var ownerLocation = LocationOfFirst(targets,
                t => t.Group is not null && AutorediNaming.ToIdentifierFragment(t.Group) == assemblySuffix);
            diagnostics.Add(Diagnostic.Create(Diagnostics.MethodNameCollision, ownerLocation, assemblySuffix));
            return;
        }

        GenerateFullAssemblyServicesDocComment(builder, assemblyName);
        builder.Method("public static", "IServiceCollection", $"{MethodPrefix}{assemblySuffix}", "this IServiceCollection services");
        builder.Block(b => EmitStandardBody(b, targets));
        builder.Line();
    }

    private static void EmitOrdered(CodeBuilder builder, IEnumerable<AutorediTarget> targets)
    {
        var ordered = targets
            .OrderByDescending(t => t.Priority)
            .ThenBy(t => t.ImplementationType, StringComparer.Ordinal);

        foreach (var target in ordered)
        {
            EmitTarget(builder, target);
        }
    }

    private static void EmitTarget(CodeBuilder builder, AutorediTarget target)
    {
        var keyLiteral = target.ServiceKey is null
            ? null
            : SymbolDisplay.FormatLiteral(target.ServiceKey, quote: true);

        if (target.InterfaceTypes.IsEmpty)
        {
            if (keyLiteral is null)
            {
                var directMethod = target.Lifetime switch
                {
                    ServiceLifetime.Singleton => "TryAddSingleton",
                    ServiceLifetime.Scoped => "TryAddScoped",
                    _ => "TryAddTransient"
                };

                builder.Line($"services.{directMethod}<{target.ImplementationType}>();");
            }
            else
            {
                var keyedMethod = target.Lifetime switch
                {
                    ServiceLifetime.Singleton => "TryAddKeyedSingleton",
                    ServiceLifetime.Scoped => "TryAddKeyedScoped",
                    _ => "TryAddKeyedTransient"
                };

                builder.Line($"services.{keyedMethod}<{target.ImplementationType}>({keyLiteral});");
            }

            return;
        }

        var factory = target.Lifetime switch
        {
            ServiceLifetime.Singleton => "Singleton",
            ServiceLifetime.Scoped => "Scoped",
            _ => "Transient"
        };

        // Every interface registration goes through TryAddAutorediDescriptor so that
        // implementations contributed by other assemblies are never dropped as duplicates.
        // Open generic service types use the typeof-based ServiceDescriptor factories; the
        // descriptor, the key and the index path are identical to closed registrations.
        foreach (var interfaceType in target.InterfaceTypes.Values)
        {
            if (interfaceType.IsOpenGeneric)
            {
                builder.Line(keyLiteral is null
                    ? $"TryAddAutorediDescriptor(services, autorediIndex, ServiceDescriptor.{factory}(typeof({interfaceType.Display}), typeof({target.ImplementationType})));"
                    : $"TryAddAutorediDescriptor(services, autorediIndex, ServiceDescriptor.Keyed{factory}(typeof({interfaceType.Display}), {keyLiteral}, typeof({target.ImplementationType})));");
                continue;
            }

            builder.Line(keyLiteral is null
                ? $"TryAddAutorediDescriptor(services, autorediIndex, ServiceDescriptor.{factory}<{interfaceType.Display}, {target.ImplementationType}>());"
                : $"TryAddAutorediDescriptor(services, autorediIndex, ServiceDescriptor.Keyed{factory}<{interfaceType.Display}, {target.ImplementationType}>({keyLiteral}));");
        }
    }

    private static void GenerateDefaultServicesDocComment(CodeBuilder builder)
    {
        builder.Line("/// <summary>");
        builder.Line("/// Registers the default (ungrouped) Autoredi services from this assembly using TryAdd semantics.");
        builder.Line("/// </summary>");
        builder.Line("/// <remarks>");
        builder.Line("/// If no groups are defined in this assembly, this method registers every service emitted by the assembly.");
        builder.Line("/// Existing descriptors are never replaced, and calling this method more than once adds no duplicates.");
        builder.Line("/// Every implementation of an interface is kept, including implementations contributed by other");
        builder.Line("/// assemblies, so <c>IEnumerable&lt;T&gt;</c> resolves them all. Resolving a single <c>T</c> still follows");
        builder.Line("/// MEDI's normal last-registration behavior; use keyed registrations when selection must be explicit.");
        builder.Line("/// </remarks>");
        builder.Line($"/// <param name=\"services\">The <see cref=\"global::Microsoft.Extensions.DependencyInjection.IServiceCollection\"/> to add registrations to.</param>");
        builder.Line("/// <returns>The same <paramref name=\"services\"/> instance, for chaining.</returns>");
    }

    private static void GenerateGroupDocComment(CodeBuilder builder, string group)
    {
        builder.Line("/// <summary>");
        var escapedGroup = AutorediNaming.EscapeXmlText(group);
        builder.Line($"/// Registers the '{escapedGroup}' Autoredi group from this assembly using TryAdd semantics.");
        builder.Line("/// </summary>");
        builder.Line("/// <remarks>");
        builder.Line("/// Only classes attributed with this group name are registered. Existing registrations");
        builder.Line("/// are never overridden, and calling this method more than once adds no duplicates.");
        builder.Line("/// </remarks>");
        builder.Line($"/// <param name=\"services\">The <see cref=\"global::Microsoft.Extensions.DependencyInjection.IServiceCollection\"/> to add registrations to.</param>");
        builder.Line("/// <returns>The same <paramref name=\"services\"/> instance, for chaining.</returns>");
    }

    private static void GenerateFullAssemblyServicesDocComment(CodeBuilder builder, string assemblyName)
    {
        builder.Line("/// <summary>");
        var escapedAssemblyName = AutorediNaming.EscapeXmlText(assemblyName);
        builder.Line($"/// Registers every Autoredi service emitted by {escapedAssemblyName} (all groups included) using TryAdd semantics.");
        builder.Line("/// </summary>");
        builder.Line("/// <remarks>");
        builder.Line("/// Registers the same service set as the default and group methods; ordering is calculated for this method.");
        builder.Line("/// Existing descriptors are never replaced, and calling this method more than once adds no duplicates.");
        builder.Line("/// To include referenced assemblies as well, use <c>AddAutorediServicesAll</c> (executables only).");
        builder.Line("/// </remarks>");
        builder.Line($"/// <param name=\"services\">The <see cref=\"global::Microsoft.Extensions.DependencyInjection.IServiceCollection\"/> to add registrations to.</param>");
        builder.Line("/// <returns>The same <paramref name=\"services\"/> instance, for chaining.</returns>");
    }

    /// <summary>
    /// The location of the first target matching a predicate, or <see cref="Location.None"/> when
    /// the attribute carried no source location. Output-stage diagnostics point at the
    /// attribute that introduced the conflict instead of reporting nothing.
    /// </summary>
    private static Location LocationOfFirst(IEnumerable<AutorediTarget> targets, Func<AutorediTarget, bool> predicate)
    {
        foreach (var target in targets)
        {
            if (predicate(target))
            {
                return target.Location is { } location ? location.ToLocation() : Location.None;
            }
        }

        return Location.None;
    }
}
